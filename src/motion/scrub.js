/**
 * Скруб — догон значения, привязанного к прокрутке.
 *
 * Беда у всех таких анимаций одна: бросок тачпада отдаёт полсекунды
 * прокрутки одним событием, значение прыгает в конец, и анимации никто
 * не видит. Приёмов против этого два, и они разные.
 *
 * Демпфирование (экспоненциальное сглаживание, оно же lerp; в GSAP это
 * scrub: <секунды>, в Lenis — smooth scroll): значение не прыгает в цель,
 * а подтягивается к ней долей за кадр. Мягко — но лаг держится всегда,
 * и на спокойной прокрутке тоже.
 *
 * Ограничение скорости (slew-rate limiting, оно же velocity clamp): сколько
 * бы прокрутки ни пришло, значение не пройдёт больше speed единиц за секунду.
 * На спокойной прокрутке не заметно вовсе — там скорость и так ниже потолка.
 * Включается только на броске и растягивает его во столько раз, во сколько
 * бросок быстрее потолка.
 *
 * Поэтому здесь главный инструмент — потолок: он чинит ровно то, что мешает,
 * и обычную прокрутку не трогает. Демпфирование добавляется там, где нужна
 * ещё и мягкость подхода к цели.
 *
 * Цена одна: значение отстаёт от прокрутки, и пока оно догоняет, кадры нужны
 * даже без новых событий. У кольца архива они и так идут — оно живёт в своём
 * цикле. Блоку, который просыпается только на прокрутку, пришлось бы просить
 * кадры самому, пока не догонит.
 *
 * Где ещё пригодится. Колода кейсов проматывается броском так же, но там
 * потолок ставить нельзя без правки геометрии: --rise карты считается от её
 * же трансформированного прямоугольника, и замедленное значение начинает
 * гоняться за собственным следствием — карта доезжает с заметным качком.
 * Сначала нужно считать положение карты по вёрстке (offsetTop и прокрутка),
 * а не по отрисованному rect; тогда обратной связи не будет и потолок ляжет
 * ровно.
 */

/**
 * Один шаг догона.
 * @param {number} current где значение сейчас
 * @param {number} target куда его ведёт прокрутка
 * @param {number} dt секунд с прошлого кадра
 * @param {{ lerp?: number, speed?: number }} [opts]
 *   lerp — доля пути за кадр при 60 Гц; 0 — без демпфирования.
 *   speed — потолок в единицах значения за секунду; 0 — без потолка.
 * @returns {number} новое значение
 */
export function scrub(current, target, dt, { lerp = 0, speed = 0 } = {}) {
  let step = target - current;
  if (lerp > 0) step *= 1 - (1 - lerp) ** (dt * 60);
  if (speed > 0) {
    const cap = speed * dt;
    if (step > cap) step = cap;
    else if (step < -cap) step = -cap;
  }
  return current + step;
}
