/**
 * Отдача — короткий тик пальцу.
 *
 * Умеет это только Vibration API, и умеет он не везде. В Chrome и Firefox
 * на Android работает; в Safari — ни на iPhone, ни на маке — его нет вовсе,
 * и в обозримом будущем не предвидится. То есть на айфоне прокрутка отдачи
 * не даст никакая вёрстка: самого канала к «Тапetic Engine» странице не дают.
 *
 * Единственная лазейка на iOS — системный переключатель <input
 * type="checkbox" switch>: при переключении пальцем он щёлкает штатной
 * отдачей. Но именно пальцем, по самому переключателю, — прокруткой его
 * не завести, так что для ленты постеров он не годится.
 *
 * Поэтому здесь честная заглушка: где отдача есть — тикает, где нет —
 * функция не заводится вовсе и вызывающий о ней не думает.
 *
 * Подряд тик не частит: на быстром броске карточки идут по пятнадцать
 * в секунду, и без паузы вышла бы не отдача, а зуд.
 *
 * И ещё: браузер не даёт вибрировать странице, которой пользователь ни разу
 * не касался, — прокрутка за касание не считается. Без проверки каждый тик
 * до первого тапа уходил бы в консоль ошибкой. Спрашиваем у браузера, был ли
 * контакт; где такого вопроса не задать, считаем, что можно.
 */

/**
 * @param {{ ms?: number, gap?: number }} [opts]
 *   ms — длительность тика; gap — не чаще, чем раз в столько миллисекунд.
 * @returns {(() => void) | null} null, если устройство отдачи не умеет
 */
export function haptics({ ms = 8, gap = 45 } = {}) {
  const able = typeof navigator !== 'undefined' && typeof navigator.vibrate === 'function';
  // на мыши отдачи не бывает; просьбу убавить движение считаем и просьбой
  // не трясти телефон
  const wanted = matchMedia('(hover: none) and (pointer: coarse)').matches
    && !matchMedia('(prefers-reduced-motion: reduce)').matches;
  if (!able || !wanted) return null;

  let last = 0;
  return () => {
    if (navigator.userActivation && !navigator.userActivation.hasBeenActive) return;
    const now = performance.now();
    if (now - last < gap) return;
    last = now;
    // устройство вправе отказать молча — и на здоровье
    try { navigator.vibrate(ms); } catch { /* без отдачи не пропадём */ }
  };
}
